export function useI18n() {
  const t = computed(() => messages[currentLang.value])

  function toggleLang() {
    currentLang.value = currentLang.value === 'zh' ? 'en' : 'zh'
    localStorage.setItem('lang', currentLang.value)
  }

  return { lang: currentLang, t, toggleLang }
}
